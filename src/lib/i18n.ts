export type Messages = (typeof messages)[Locale];

export function localizedGroupTitle(
  id: "odoo" | "industry",
  t: Messages,
) {
  return t.groups[id];
}

export function localizedServiceItem(href: string, t: Messages) {
  switch (href) {
    case "/services/erp-implementation":
      return { label: t.items.erp };
    case "/services/business-process-audit":
      return { label: t.items.audit };
    case "/services/accounting-finance-reporting":
      return { label: t.items.accounting };
    case "/services/real-estate":
      return { label: t.items.realEstate, description: t.items.realEstateDesc };
    default:
      return { label: href };
  }
}
